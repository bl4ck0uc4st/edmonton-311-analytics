"""Static preview charts rendered straight from the warehouse (matplotlib).

These are not the Power BI report; they are pipeline-generated previews that the
scheduled workflow refreshes from the live data and embeds in the README, so the
repository always shows current numbers even before the .pbix is opened. Every
figure carries a provenance footer (live data vs synthetic sample) so nothing can
be mistaken for official City reporting.
"""

