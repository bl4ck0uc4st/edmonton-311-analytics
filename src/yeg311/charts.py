def _thousands(x, _pos=None) -> str:
    return f"{x:,.0f}"


def _footer(fig: plt.Figure, provenance: str) -> None:
    fig.text(0.01, 0.01, provenance, fontsize=7.5, color=INK2, ha="left", va="bottom")


def _save(fig: plt.Figure, path: Path) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    fig.tight_layout(rect=(0, 0.06, 1, 0.97))
    fig.savefig(path, dpi=150, bbox_inches="tight", facecolor=SURFACE)
    plt.close(fig)
    log.info("Chart written: %s", path)
    return path


def _provenance(con) -> tuple[str, bool]:
    info = dict(con.execute("SELECT key, value FROM meta.build_info").fetchall())
    synthetic = info.get("data_source", "").startswith("synthetic")
    built = (info.get("built_at_utc") or "")[:10]
    if synthetic:
        return (
            f"SYNTHETIC SAMPLE DATA generated by `yeg311 sample` (not City of Edmonton data) · built {built}",
            True,
        )
    return (
        f"Source: City of Edmonton Open Data, 311 Requests (data.edmonton.ca/d/q7ua-agfg) · pipeline build {built}",
        False,
    )


def _banner(fig: plt.Figure, synthetic: bool) -> None:
    if synthetic:
        fig.text(
            0.99, 0.985, "SYNTHETIC SAMPLE", fontsize=9, color=ORANGE, ha="right", va="top", weight="bold"
        )


def chart_monthly_volume(con, out: Path, prov: str, synthetic: bool) -> Path:
    df = con.execute(
        """
        SELECT d.year_month, count(*) AS requests, count(*) FILTER (WHERE f.is_service_request) AS service_requests
        FROM gold.fact_service_request f JOIN gold.dim_date d ON d.date_key = f.created_date_key
        GROUP BY 1 ORDER BY 1
        """
    ).df()
    if len(df) > 1:
        df = df.iloc[:-1]  # drop the partial current month
    x = np.arange(len(df))
    fig, ax = plt.subplots(figsize=(10, 4.8))
    ax.plot(x, df["requests"], color=BLUE, linewidth=2, label="All 311 requests")
    ax.plot(
        x,
        df["service_requests"],
        color=ORANGE,
        linewidth=2,
        label="Service requests (referred to a business area)",
    )
    for series in ("requests", "service_requests"):
        ax.annotate(
            f"{df[series].iloc[-1]:,.0f}",
            (x[-1], df[series].iloc[-1]),
            xytext=(6, 0),
            textcoords="offset points",
            fontsize=8.5,
            color=INK,
            va="center",
        )
    step = max(1, -(-len(df) // 9))
    ax.set_xticks(x[::step])
    ax.set_xticklabels(df["year_month"].iloc[::step], rotation=0)
    ax.yaxis.set_major_formatter(FuncFormatter(_thousands))
    ax.set_ylim(bottom=0)
    ax.set_xlim(x[0] - 0.5, x[-1] + 2.5)
    ax.set_title("Monthly 311 volume: all requests vs service requests")
    ax.legend(loc="upper left", ncol=2)
    ax.grid(axis="x", visible=False)
    _footer(fig, prov)
    _banner(fig, synthetic)
    return _save(fig, out / "chart_monthly_volume.png")


def chart_top_categories(con, out: Path, prov: str, synthetic: bool) -> Path:
    df = con.execute(
        """
        SELECT s.service_category, count(*) AS n,
               median(f.resolution_days) FILTER (WHERE f.is_closed) AS median_days
        FROM gold.fact_service_request f JOIN gold.dim_service s USING (service_key)
        WHERE f.is_service_request
        GROUP BY 1 ORDER BY n DESC LIMIT 10
        """
    ).df()[::-1]
    fig, ax = plt.subplots(figsize=(10, 5.2))
    bars = ax.barh(df["service_category"], df["n"], color=BLUE, height=0.62)
    for b, n, med in zip(bars, df["n"], df["median_days"], strict=True):
        label = f"{n:,.0f}" + (f"   median {med:.1f} d" if med == med else "")
        ax.text(
            b.get_width() + df["n"].max() * 0.01,
            b.get_y() + b.get_height() / 2,
            label,
            va="center",
            fontsize=8.5,
            color=INK,
        )
    ax.set_xlim(0, df["n"].max() * 1.32)
    ax.xaxis.set_major_formatter(FuncFormatter(_thousands))
    ax.set_title("Top 10 service-request categories (volume and median days to close)")
    ax.grid(axis="y", visible=False)
    _footer(fig, prov)
    _banner(fig, synthetic)
    return _save(fig, out / "chart_top_categories.png")


def chart_sla_by_area(con, out: Path, prov: str, synthetic: bool) -> Path:
    df = con.execute(
        """
        SELECT s.service_area,
               100.0 * count(*) FILTER (WHERE f.sla_met) / count(*) FILTER (WHERE f.sla_met IS NOT NULL) AS pct,
               count(*) FILTER (WHERE f.sla_met IS NOT NULL) AS evaluated
        FROM gold.fact_service_request f JOIN gold.dim_service s USING (service_key)
        WHERE f.is_service_request
        GROUP BY 1 HAVING count(*) FILTER (WHERE f.sla_met IS NOT NULL) >= 200
        ORDER BY pct DESC LIMIT 14
        """
    ).df()[::-1]
    fig, ax = plt.subplots(figsize=(10, 5.4))
    ax.barh(df["service_area"], df["pct"], color=BLUE, height=0.62)
    ax.axvline(85, color=INK, linestyle="--", linewidth=1.2)
    ax.text(85, len(df) - 0.35, " goal 85%", fontsize=8.5, color=INK, va="bottom")
    for i, (pct, n) in enumerate(zip(df["pct"], df["evaluated"], strict=True)):
        label = f"{pct:.0f}%  (n={n:,.0f})"
        if pct >= 35:
            ax.text(pct - 1.2, i, label, va="center", ha="right", fontsize=8.5, color="white")
        else:
            ax.text(pct + 1.2, i, label, va="center", ha="left", fontsize=8.5, color=INK)
    ax.set_xlim(0, 100)
    ax.set_ylim(-0.6, len(df) + 0.2)
    ax.xaxis.set_major_formatter(PercentFormatter())
    ax.set_title("Closed service requests resolved within the illustrative target, by business area")
    ax.grid(axis="y", visible=False)
    _footer(fig, prov + " · targets are illustrative (seeds/sla_targets.csv), not City of Edmonton standards")
    _banner(fig, synthetic)
    return _save(fig, out / "chart_sla_by_area.png")


def chart_backlog_trend(con, out: Path, prov: str, synthetic: bool) -> Path:
    df = con.execute(
        """
        WITH month_end AS (
            SELECT year_month, max(date_key) AS date_key FROM gold.dim_date
            WHERE date_key IN (SELECT DISTINCT date_key FROM gold.fact_backlog_snapshot) GROUP BY 1
        )
        SELECT m.year_month, sum(b.open_requests) AS open_total, sum(b.open_over_30_days) AS over_30
        FROM month_end m JOIN gold.fact_backlog_snapshot b USING (date_key)
        GROUP BY 1 ORDER BY 1
        """
    ).df()
    x = np.arange(len(df))
    under_30 = df["open_total"] - df["over_30"]
    fig, ax = plt.subplots(figsize=(10, 4.8))
    ax.stackplot(
        x,
        under_30,
        df["over_30"],
        colors=[BLUE, ORANGE],
        labels=["Open 30 days or less", "Open more than 30 days"],
        alpha=0.95,
    )
    ax.annotate(
        f"{df['open_total'].iloc[-1]:,.0f} open",
        (x[-1], df["open_total"].iloc[-1]),
        xytext=(6, 0),
        textcoords="offset points",
        fontsize=8.5,
        color=INK,
        va="center",
    )
    step = max(1, -(-len(df) // 9))
    ax.set_xticks(x[::step])
    ax.set_xticklabels(df["year_month"].iloc[::step])
    ax.yaxis.set_major_formatter(FuncFormatter(_thousands))
    ax.set_xlim(x[0], x[-1] + 2.5)
    ax.set_title("Open service requests at month end (periodic snapshot fact), by age")
    ax.legend(loc="upper center", bbox_to_anchor=(0.5, -0.1), ncol=2)
    ax.grid(axis="x", visible=False)
    _footer(fig, prov)
    _banner(fig, synthetic)
    return _save(fig, out / "chart_backlog_trend.png")


def chart_channel_mix(con, out: Path, prov: str, synthetic: bool) -> Path:
    df = con.execute(
        """
        SELECT d.year_quarter,
               100.0 * count(*) FILTER (WHERE i.interaction_channel = 'Phone Call') / count(*) AS phone,
               100.0 * count(*) FILTER (WHERE i.interaction_channel = 'Mobile App') / count(*) AS mobile,
               100.0 * count(*) FILTER (WHERE i.interaction_channel = 'Web Form') / count(*) AS web,
               100.0 * count(*) FILTER (WHERE i.interaction_channel NOT IN ('Phone Call','Mobile App','Web Form')) / count(*) AS other
        FROM gold.fact_service_request f
        JOIN gold.dim_date d ON d.date_key = f.created_date_key
        JOIN gold.dim_intake i USING (intake_key)
        GROUP BY 1 ORDER BY 1
        """
    ).df()
    x = np.arange(len(df))
    fig, ax = plt.subplots(figsize=(10, 4.8))
    ax.stackplot(
        x,
        df["phone"],
        df["mobile"],
        df["web"],
        df["other"],
        colors=[BLUE, ORANGE, AQUA, YELLOW],
        labels=["Phone call", "Mobile app", "Web form", "Email / map / other"],
        alpha=0.95,
    )
    cum = 0.0
    for col in ("phone", "mobile", "web"):
        val = df[col].iloc[-1]
        ax.annotate(
            f"{val:.0f}%",
            (x[-1], cum + val / 2),
            xytext=(6, 0),
            textcoords="offset points",
            fontsize=8.5,
            color=INK,
            va="center",
        )
        cum += val
    ax.set_xticks(x)
    ax.set_xticklabels(df["year_quarter"], fontsize=8)
    ax.set_xlim(x[0], x[-1] + 1.2)
    ax.set_ylim(0, 100)
    ax.yaxis.set_major_formatter(PercentFormatter())
    ax.set_title("How residents contact 311: channel share by quarter")
    ax.legend(loc="upper center", bbox_to_anchor=(0.5, -0.1), ncol=4)
    ax.grid(axis="x", visible=False)
    _footer(fig, prov)
    _banner(fig, synthetic)
    return _save(fig, out / "chart_channel_mix.png")


def chart_intake_heatmap(con, out: Path, prov: str, synthetic: bool) -> Path:
    df = con.execute(
        """
        SELECT d.day_of_week, f.created_hour, count(*) AS n
        FROM gold.fact_service_request f JOIN gold.dim_date d ON d.date_key = f.created_date_key
        GROUP BY 1, 2
        """
    ).df()
    grid = np.zeros((7, 24))
    for dow, hour, n in df.itertuples(index=False):
        grid[int(dow) - 1, int(hour)] = n
    cmap = matplotlib.colors.LinearSegmentedColormap.from_list("blues", SEQ_BLUES)
    fig, ax = plt.subplots(figsize=(10, 3.9))
    im = ax.imshow(grid, aspect="auto", cmap=cmap)
    ax.set_yticks(range(7))
    ax.set_yticklabels(["Mon", "Tue", "Wed", "Thu", "Fri", "Sat", "Sun"])
    ax.set_xticks(range(0, 24, 2))
    ax.set_xticklabels([f"{h:02d}:00" for h in range(0, 24, 2)])
    ax.grid(False)
    ax.set_title("When requests arrive: weekday x hour of day")
    cb = fig.colorbar(im, ax=ax, fraction=0.025, pad=0.02)
    cb.ax.yaxis.set_major_formatter(FuncFormatter(_thousands))
    cb.set_label("requests", color=INK2)
    _footer(fig, prov)
    _banner(fig, synthetic)
    return _save(fig, out / "chart_intake_heatmap.png")


CHARTS = (
    chart_monthly_volume,
    chart_top_categories,
    chart_sla_by_area,
    chart_backlog_trend,
    chart_channel_mix,
    chart_intake_heatmap,
)


def render_charts(settings: Settings, out_dir: Path | None = None) -> list[Path]:
    out = Path(out_dir or settings.export_dir / "charts")
    con = connect(settings, read_only=True)
    try:
        prov, synthetic = _provenance(con)
        return [fn(con, out, prov, synthetic) for fn in CHARTS]
    finally:
        con.close()
